#!/usr/bin/env python3
"""Turn a planner occupancy grid into a Gazebo world, so the physics world and the planner map are the same map.
Usage: grid_to_sdf.py            regenerates every world in worlds/
Later, a surveyed Cherry-floor grid goes through the same function."""
import os, sys, re
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE) if os.path.basename(HERE) != 'scripts' else os.path.dirname(HERE)
REPO = os.path.abspath(os.path.join(PKG, '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'planner', 'py'))
from worlds import gap_world, corridor_world, RES  # noqa: E402

WALL_H = 2.0

def merge_rects(g):
    """Greedy merge of occupied cells into rectangles: row runs, then stack identical runs vertically."""
    H, W = g.shape; runs = {}
    for j in range(H):
        i = 0
        while i < W:
            if g[j, i]:
                k = i
                while k < W and g[j, k]: k += 1
                runs.setdefault((i, k), []).append(j); i = k
            else: i += 1
    rects = []
    for (i0, i1), rows in runs.items():
        rows.sort(); s = rows[0]; p = rows[0]
        for r in rows[1:] + [None]:
            if r is None or r != p + 1: rects.append((i0, i1, s, p + 1)); s = r
            p = r if r is not None else p
    return rects

def rover_fragment():
    txt = open(os.path.join(PKG, 'models', 'rover_mega', 'model.sdf')).read()
    return txt[txt.index('<model'):txt.rindex('</model>') + len('</model>')]

def world_sdf(g, name, spawn):
    boxes = []
    for n, (i0, i1, j0, j1) in enumerate(merge_rects(g)):
        x0, x1, y0, y1 = i0 * RES, i1 * RES, j0 * RES, j1 * RES
        boxes.append(f'''    <model name="wall_{n}"><static>true</static><pose>{(x0+x1)/2:.3f} {(y0+y1)/2:.3f} {WALL_H/2:.2f} 0 0 0</pose>
      <link name="l"><collision name="c"><geometry><box><size>{x1-x0:.3f} {y1-y0:.3f} {WALL_H}</size></box></geometry></collision>
      <visual name="v"><geometry><box><size>{x1-x0:.3f} {y1-y0:.3f} {WALL_H}</size></box></geometry>
      <material><ambient>0.75 0.75 0.78 1</ambient><diffuse>0.75 0.75 0.78 1</diffuse></material></visual></link></model>''')
    rover = rover_fragment().replace('<model name="rover">', f'<model name="rover"><pose>{spawn[0]} {spawn[1]} 0.15 0 0 {spawn[2]}</pose>', 1)
    return f'''<?xml version="1.0"?>
<!-- GENERATED by scripts/grid_to_sdf.py from planner/py/worlds.py. Do not edit by hand. -->
<sdf version="1.9">
  <world name="{name}">
    <physics name="p" type="ode"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <light type="directional" name="sun"><cast_shadows>false</cast_shadows><pose>0 0 10 0 0 0</pose><diffuse>0.9 0.9 0.9 1</diffuse><direction>-0.3 0.2 -1</direction></light>
    <model name="ground"><static>true</static><pose>{g.shape[1]*RES/2} {g.shape[0]*RES/2} 0 0 0 0</pose><link name="l">
      <collision name="c"><geometry><plane><normal>0 0 1</normal><size>{g.shape[1]*RES+4} {g.shape[0]*RES+4}</size></plane></geometry></collision>
      <visual name="v"><geometry><plane><normal>0 0 1</normal><size>{g.shape[1]*RES+4} {g.shape[0]*RES+4}</size></plane></geometry>
      <material><ambient>0.55 0.55 0.5 1</ambient><diffuse>0.55 0.55 0.5 1</diffuse></material></visual></link></model>
{chr(10).join(boxes)}
    {rover}
  </world>
</sdf>
'''

def main():
    out = os.path.join(PKG, 'worlds'); os.makedirs(out, exist_ok=True)
    for gap in (0.70, 0.80, 0.85, 0.90, 1.20, 1.32):
        name = 'gap_%s' % ('%.2f' % gap).replace('.', 'p')
        open(os.path.join(out, name + '.sdf'), 'w').write(world_sdf(gap_world(gap), name, (3.0, 5.0, 0.0)))
    open(os.path.join(out, 'corridor.sdf'), 'w').write(world_sdf(corridor_world(0), 'corridor', (3.0, 7.2, 0.0)))
    print('worlds written to', out)

if __name__ == '__main__':
    main()
